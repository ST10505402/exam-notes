    // Capture -> validate -> calculate -> display -> save
    void processRental() {
        String customerName = txfCustomerName.getText().trim();
        String vehicleType = (String) cboVehicle.getSelectedItem();

        // Convert the days once; letters show a message instead of crashing
        int numberOfDays;
        try {
            numberOfDays = Integer.parseInt(txfNumberOfDays.getText().trim());
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Number of days must be a whole number.",
                    "Invalid input", JOptionPane.ERROR_MESSAGE);
            txfNumberOfDays.requestFocus();
            return;
        }

        // All validation rules live in the CarHire class
        RentalData rentalData = new RentalData(customerName, vehicleType, numberOfDays);
        if (!carHire.ValidateData(rentalData)) {
            JOptionPane.showMessageDialog(this,
                    "Customer name is required and the number of days must be from 1 to 30.",
                    "Invalid input", JOptionPane.ERROR_MESSAGE);
            return;
        }

        double dailyRate = carHire.GetDailyRate(vehicleType);
        double totalCost = carHire.CalculateRentalCost(vehicleType, numberOfDays);
        boolean discountApplied = carHire.IsDiscountApplied(numberOfDays);

        String report = buildReport(rentalData, dailyRate, discountApplied, totalCost);
        txaReport.setText(report);            // stays on screen (Q.2.4)
        saveReport(report);                   // Q.2.5
    }

    // Report lines exactly as the sample
    static String buildReport(RentalData data, double dailyRate, boolean discountApplied, double totalCost) {
        return "CUSTOMER NAME: " + data.getCustomerName() + "\n"
                + "VEHICLE: " + data.getVehicleType() + "\n"
                + "NUMBER OF DAYS: " + data.getNumberOfDays() + "\n"
                + "DAILY RATE: " + String.format("R %.2f", dailyRate) + "\n"
                + "DISCOUNT APPLIED: " + (discountApplied ? "Yes" : "No") + "\n"
                + "TOTAL RENTAL COST: " + String.format("R %.2f", totalCost);
    }

    // rental.txt = heading + stars + report + stars (overwritten for each rental)
    private void saveReport(String report) {
        String stars = "*".repeat(30);
        File file = new File(FILE_NAME);
        try (BufferedWriter writer = new BufferedWriter(new FileWriter(file))) {
            writer.write("VAAL CAR HIRE RENTAL REPORT");
            writer.newLine();
            writer.write(stars);
            writer.newLine();
            writer.write(report);
            writer.newLine();
            writer.write(stars);
            writer.newLine();
        } catch (IOException e) {
            JOptionPane.showMessageDialog(this, "Could not save the report: " + e.getMessage(),
                    "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        JOptionPane.showMessageDialog(this, "Report saved to:\n" + file.getAbsolutePath());
    }

