    // Q.2.2 Load: calculate from the stored data and display the four results
    void loadUsageData() {
        txaResults.setText("Total Usage: " + waterUsage.GetTotalUsage() + " kl\n"
                + "Average Usage: " + Math.round(waterUsage.GetAverageUsage()) + " kl\n"
                + "Highest Reading: " + waterUsage.GetHighestReading() + " kl\n"
                + "Readings over limit: " + waterUsage.GetReadingsOverLimit());
        lblMonthsProcessed.setText("Months Processed: " + waterUsage.GetMonthsProcessed());
    }

    // Q.2.2 Save: usage_log.txt = heading + stars + the text area's results + stars
    void saveUsageData() {
        if (txaResults.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Load the usage data before saving.");
            return;
        }
        String stars = "*".repeat(30);
        File file = new File(FILE_NAME);
        try (BufferedWriter writer = new BufferedWriter(new FileWriter(file))) {
            writer.write("USAGE LOG");
            writer.newLine();
            writer.write(stars);
            writer.newLine();
            writer.write(txaResults.getText());
            writer.newLine();
            writer.write(stars);
            writer.newLine();
        } catch (IOException e) {
            JOptionPane.showMessageDialog(this, "Could not save: " + e.getMessage(),
                    "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        JOptionPane.showMessageDialog(this, "Usage data saved to:\n" + file.getAbsolutePath());
    }

    // Q.2.3 Clear: empty the text area and the Months Processed label
    void clearForm() {
        txaResults.setText("");
        lblMonthsProcessed.setText("Months Processed:");
    }

